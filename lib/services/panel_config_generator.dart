import '../models/device_model.dart';
import '../models/panel_wiring.dart';
import 'panel/panel_settings.dart';

/// Builds the panel controller's `include/panel_config.h` from the app's
/// machines, connection settings and panel wiring, so machine IDs, the
/// panel ID and the broker match the app exactly.
class PanelConfigGenerator {
  const PanelConfigGenerator._();

  /// The header for [devices]. [wifiPassword] and [panelPassword] end up in
  /// the file, so it must be kept private (it's git-ignored in the
  /// firmware project).
  static String generate({
    required PanelSettings settings,
    required PanelWiring wiring,
    required List<DeviceModel> devices,
    required String wifiPassword,
    required String panelPassword,
    required DateTime now,
  }) {
    final b = StringBuffer();
    void line([String text = '']) => b.writeln(text);
    String stamp(DateTime t) =>
        '${t.year}-${_two(t.month)}-${_two(t.day)} ${_two(t.hour)}:${_two(t.minute)}';

    line('#pragma once');
    line('// Panel configuration, generated by the SMART-AUTOMIX app');
    line('// (Settings > Panel setup) on ${stamp(now)}.');
    line(
        '// It holds the WiFi and broker passwords: keep it private. Save it as');
    line('// firmware/esp32-panel/include/panel_config.h (git-ignored).');
    line();
    line('#include <vector>');
    line();
    line('#include "machine_config.h"');
    line();
    line(
        '// ---- Network ----------------------------------------------------------------');
    line();
    line('#define WIFI_SSID ${_c(wiring.wifiSsid)}');
    line('#define WIFI_PASSWORD ${_c(wifiPassword)}');
    line();
    line('#define MQTT_HOST ${_c(settings.host)}');
    line('#define MQTT_PORT ${settings.tcpPort}');
    line('#define MQTT_USE_TLS ${settings.useTls ? 1 : 0}');
    line('#define MQTT_USERNAME ${_c(wiring.panelUsername)}');
    line('#define MQTT_PASSWORD ${_c(panelPassword)}');
    if (settings.useTls) {
      line("// Paste the broker's CA certificate (PEM) here; the build fails");
      line('// without it.');
    }
    line('#define MQTT_CA_CERT ""');
    line('#define MQTT_ALLOW_INSECURE_TLS 0');
    line();
    line('#define PANEL_ID ${_c(settings.panelId)}');
    line();
    line(
        '// ---- Timing -----------------------------------------------------------------');
    line();
    line('#define SENSOR_INTERVAL_MS 5000');
    line('#define CONFIRM_DELAY_MS 300');
    line('#define MIN_START_GAP_MS 2000');
    line('#define CMD_MAX_AGE_MS 10000');
    line('#define NTP_SERVER "pool.ntp.org"');
    line('#define TIMEZONE "EAT-3"  // East Africa Time, UTC+3');
    line('#define ENERGY_KEEP_DAYS 400');
    line();
    line(
        '// ---- PZEM-004T v3 energy meters ---------------------------------------------');
    line();
    line('#define PZEM_RX_PIN ${PanelWiring.pzemRxPin}');
    line('#define PZEM_TX_PIN ${PanelWiring.pzemTxPin}');
    line(
        '// Set to an address (1-247) to give one PZEM its address; see the README.');
    line('#define PZEM_SET_ADDRESS 0');
    line();
    line(
        '// ---- Supply protection ------------------------------------------------------');
    line();
    line('#define SUPPLY_PROTECTION 1');
    line('#define UNDERVOLTAGE_V ${wiring.undervoltage}');
    line('#define OVERVOLTAGE_V ${wiring.overvoltage}');
    line('#define PHASE_LOSS_V 100');
    line('#define SUPPLY_TRIP_DELAY_MS 5000');
    line('#define SUPPLY_STABLE_MS 60000');
    line();
    line(
        '// ---- Generator --------------------------------------------------------------');
    line();
    line('#define GENERATOR_PIN ${wiring.generatorPin ?? 'NO_PIN'}');
    line('#define GENERATOR_ACTIVE_LOW true');
    line();
    line(
        '// ---- Machines ---------------------------------------------------------------');
    line();
    line('//  id    relay  activeLow  feedback  fbActiveLow  pzem  threePhase');
    line('static const MachineConfig MACHINES[] = {');
    for (final d in devices) {
      final w = wiring.machines[d.id];
      if (w == null) continue;
      final fields = [
        _c(d.id),
        '${w.relayPin}',
        '${w.relayActiveLow}',
        '${w.feedbackPin ?? 'NO_PIN'}',
        '${w.feedbackActiveLow}',
        w.pzemAddress == null ? 'NO_PZEM' : _hex(w.pzemAddress!),
        '${d.phase == 'three'}',
      ];
      line('    {${fields.join(', ')}},  // ${_comment(d.name)}');
    }
    line('};');
    line();
    line('// PZEMs on the main incomer (none, one, or one per phase).');
    line('static const std::vector<uint8_t> METER_PZEMS = '
        '{${wiring.meterAddresses.map(_hex).join(', ')}};');
    return b.toString();
  }

  static String _two(int n) => n.toString().padLeft(2, '0');

  static String _hex(int n) =>
      '0x${n.toRadixString(16).toUpperCase().padLeft(2, '0')}';

  /// A C string literal.
  static String _c(String s) {
    final escaped = s
        .replaceAll(r'\', r'\\')
        .replaceAll('"', r'\"')
        .replaceAll('\n', r'\n')
        .replaceAll('\r', '');
    return '"$escaped"';
  }

  /// Text that is safe inside a `//` comment.
  static String _comment(String s) =>
      s.replaceAll(RegExp(r'[\r\n]+'), ' ').trim();
}
